import { describe, it, expect, afterEach, vi, type Mock } from "vitest";
import crypto from "crypto";
import { Writable } from "node:stream";
import request from "supertest";
import { createApp } from "../app";
import { uniquePhone } from "./helpers";

// P3a-1 / P3a-2 — production must never leak OTP codes or phone numbers into
// the log stream, and OTP codes must come from a CSPRNG. This file pins:
//  - the console SMS provider prints in dev, and in production prints ONLY
//    for phones in ADMIN_PHONES (the operator's interim log-OTP sign-in);
//  - pino redaction turns phone/to/body/smsBody fields into [REDACTED];
//  - the OTP code is generated by crypto.randomInt, never Math.random.

const PROD_SECRET = "redact-test-secret-0123456789abcdef0123456789abcdef";
const ADMIN_PHONE = "+923145578207";
const DONOR_PHONE = "+923001112233";

afterEach(() => {
  process.env.NODE_ENV = "test";
  delete process.env.JWT_SECRET;
  delete process.env.FRONTEND_URL;
  delete process.env.MONGO_URI;
  delete process.env.ADMIN_PHONES;
  delete process.env.LOG_LEVEL;
  vi.restoreAllMocks();
  vi.resetModules();
});

// Filter helper: dotenv prints its own "tip" line through console.log during
// module import, so assertions target the [SMS:console] lines specifically.
function smsLogCalls(spy: ReturnType<typeof vi.spyOn>): unknown[][] {
  return spy.mock.calls.filter((c) => String(c[0]).includes("[SMS:console]"));
}

describe("console SMS provider log gating (P3a-1)", () => {
  it("prints the OTP in development for any phone (dev delivery mechanism)", async () => {
    const logSpy = vi.spyOn(console, "log").mockImplementation(() => {});
    const { getSmsProvider } = await import("../lib/smsProvider");
    const ok = await getSmsProvider().sendSms(
      DONOR_PHONE,
      "Your BloodRadar verification code is 123456. It expires in 5 minutes. Do not share it with anyone."
    );
    expect(ok).toBe(true);
    expect(smsLogCalls(logSpy)).toHaveLength(1);
    expect(smsLogCalls(logSpy)[0][0]).toContain("123456");
  });

  it("production prints ONLY for phones in ADMIN_PHONES", async () => {
    process.env.NODE_ENV = "production";
    process.env.JWT_SECRET = PROD_SECRET;
    process.env.FRONTEND_URL = "https://bloodradar.test";
    process.env.MONGO_URI = "mongodb://127.0.0.1:59999/definitely-unreachable";
    process.env.ADMIN_PHONES = ADMIN_PHONE;
    process.env.LOG_LEVEL = "silent"; // keep the console-provider boot warning out of the test run
    vi.resetModules();

    const logSpy = vi.spyOn(console, "log").mockImplementation(() => {});
    const { getSmsProvider } = await import("../lib/smsProvider");

    // A real donor's OTP must never reach the log stream in production.
    const donorOk = await getSmsProvider().sendSms(
      DONOR_PHONE,
      "Your BloodRadar verification code is 654321. It expires in 5 minutes. Do not share it with anyone."
    );
    expect(donorOk).toBe(true);
    expect(smsLogCalls(logSpy)).toHaveLength(0);

    // The operator's own admin phone keeps the interim log-OTP sign-in alive
    // (see DEPLOYMENT-RUNBOOK § smoke) — code printed, but only for them.
    await getSmsProvider().sendSms(
      ADMIN_PHONE,
      "Your BloodRadar verification code is 999888. It expires in 5 minutes. Do not share it with anyone."
    );
    expect(smsLogCalls(logSpy)).toHaveLength(1);
    expect(smsLogCalls(logSpy)[0][0]).toContain("999888");
  });
});

describe("pino log redaction (P3a-1)", () => {
  it("redacts phone/to/body/smsBody fields while keeping harmless fields", async () => {
    const { createLogger } = await import("../lib/logger");
    const lines: string[] = [];
    const sink = new Writable({
      write(chunk, _enc, cb) {
        lines.push(String(chunk));
        cb();
      },
    });
    const log = createLogger({ level: "info", destination: sink });
    log.info(
      {
        phone: "+923145578207",
        smsBody: "O+ ISLAMABAD",
        to: "+923001112233",
        body: "Your BloodRadar verification code is 777000.",
        nested: { phone: "+923334445556" },
        safe: "visible",
      },
      "sms-related log line"
    );
    // pino writes through the stream asynchronously; one tick is enough.
    await new Promise((resolve) => setImmediate(resolve));

    expect(lines.length).toBe(1);
    const entry = JSON.parse(lines[0]);
    expect(entry.phone).toBe("[REDACTED]");
    expect(entry.smsBody).toBe("[REDACTED]");
    expect(entry.to).toBe("[REDACTED]");
    expect(entry.body).toBe("[REDACTED]");
    expect(entry.nested.phone).toBe("[REDACTED]");
    expect(entry.safe).toBe("visible");
    expect(entry.msg).toBe("sms-related log line");
  });
});

describe("OTP generation (P3a-2)", () => {
  it("generates the code with crypto.randomInt, never Math.random", async () => {
    const phone = uniquePhone();
    // If the old Math.random() path were still live, Math.random()===0 would
    // force the code to "100000" every time. The CSPRNG path instead returns
    // exactly what crypto.randomInt produces.
    const mathSpy = vi.spyOn(Math, "random").mockReturnValue(0);
    // crypto.randomInt has a callback overload (returns void), so pin the
    // two-arg sync signature the OTP service actually uses.
    const randomIntSpy = vi.spyOn(crypto, "randomInt") as unknown as Mock<
      (min: number, max: number) => number
    >;
    randomIntSpy.mockReturnValue(482913);
    try {
      const app = createApp();
      const res = await request(app).post("/api/auth/otp/request").send({ phone });
      expect(res.status).toBe(200);
      expect(res.body.devOtp).toBe("482913");
      expect(mathSpy).not.toHaveBeenCalled();
      expect(randomIntSpy).toHaveBeenCalledWith(100000, 1000000);
    } finally {
      mathSpy.mockRestore();
      randomIntSpy.mockRestore();
    }
  });
});
